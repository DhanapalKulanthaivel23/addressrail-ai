import assert from 'node:assert/strict';
import {chromium} from 'playwright';
const browser=await chromium.launch({headless:true});
try{
 const page=await browser.newPage();
 const errors=[];page.on('pageerror',error=>errors.push(error.message));
 await page.goto(process.env.WORKBENCH_URL||'http://127.0.0.1:8765/studio/workbench/');
 assert.equal(await page.locator('aside').count(),1,'MT/MX must be within the existing product shell');
 assert.equal(await page.locator('aside .message-nav').count(),1,'MT/MX link must be first in the sidebar');
 assert.match((await page.locator('aside .message-nav').textContent())||'',/MT \/ MX Message Validator/);
 assert.equal(await page.getByText(/Browser-only structural review/).count(),0);
 assert.equal(await page.getByText(/Explain errors with RAG/).count(),0);
 assert.equal(await page.getByRole('heading',{name:'MT / MX Validator'}).count(),1);

 await page.getByRole('button',{name:/SWIFT MT messages/}).click();
 await page.getByRole('button',{name:'Load MT example'}).click();
 await page.getByRole('button',{name:'Check MT message'}).click();
 assert.match(await page.getByTestId('raw-validation-status').textContent(),/MT103/);
 assert.equal(await page.getByText(/LOCAL_SYNTAX_SUBSET_ONLY/).count(),0);
 const input=page.getByLabel('MT message input');
 await input.fill((await input.inputValue()).replace(/-}$/, ''));
 await page.getByRole('button',{name:'Check MT message'}).click();
 assert.match(await page.getByTestId('raw-issues').textContent(),/FIN message structure error/);
 await page.getByRole('button',{name:'Apply fix & recheck'}).click();
 assert.match(await page.getByTestId('raw-validation-status').textContent(),/No errors found by available checks/);
 await page.getByRole('button',{name:/ISO 20022 MX messages/}).click();
 await page.getByRole('button',{name:'Load MX example'}).click();
 await page.getByRole('button',{name:'Check MX message'}).click();
 assert.match(await page.getByTestId('raw-issues').textContent(),/Invalid bank identifier/);
 await page.getByRole('button',{name:'Apply fix & recheck'}).click();
 assert.ok((await page.getByLabel('MX message input').inputValue()).includes('<BICFI>BANKGB2LXXX</BICFI>'));
 assert.match(await page.getByTestId('raw-validation-status').textContent(),/No errors found by available checks/);
 await page.getByLabel('MX message input').fill('<!DOCTYPE Document><Document/>');
 await page.getByRole('button',{name:'Check MX message'}).click();
 assert.match(await page.getByTestId('raw-issues').textContent(),/Unsafe XML declaration/);
 await page.getByRole('checkbox').count().then(count=>assert.equal(count,1));
 await page.locator('aside .subproducts button[aria-current="page"]').click();
 assert.equal(await page.getByRole('button',{name:'Payment testing',exact:true}).count(),1);
 assert.equal(await page.locator('aside .message-nav').count(),1);
 await page.locator('aside .message-nav').click();
 assert.equal(await page.getByRole('button',{name:/SWIFT MT messages/}).count(),1);
 await page.setViewportSize({width:375,height:812});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
 assert.deepEqual(errors,[]);
 console.log('MT/MX GATEWAY PASS: choice, samples, error repair, MX correction, malicious XML rejection and mobile');
}finally{await browser.close()}
